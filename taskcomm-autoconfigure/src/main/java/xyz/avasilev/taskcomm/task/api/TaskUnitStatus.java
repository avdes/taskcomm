package xyz.avasilev.taskcomm.task.api;

/**
 * Статус подзадачи (docs/adr/0068-expansion-children-statuses.md). Значения в базе пишутся ровно
 * как здесь. У подзадачи нет детей, поэтому нет {@code AWAITING_CHILDREN} и {@code WARNING}.
 */
public enum TaskUnitStatus {

    /** Порождена, но попытка раскрытия родителя ещё не закрыта успехом; не захватывается, но незавершена. */
    AWAITING_PARENT,

    /** Ждёт захвата, в том числе повтора. */
    PENDING,

    /** Захвачена и обрабатывается. */
    RUNNING,

    /** Выполнена. */
    SUCCEEDED,

    /** Не выполнена: попытки исчерпаны или повтор запрещён процессором. */
    FAILED,

    /** Работа не сделана из-за отмены. */
    CANCELLED,

    /** Выполнять не надо. */
    SKIPPED,

    /** Дитя неуспешной попытки раскрытия: работа не начиналась и не начнётся; в агрегат не входит. */
    ABANDONED
}
