package xyz.avasilev.taskcomm.task.api;

/**
 * Статус задачи целиком (docs/adr/0068-expansion-children-statuses.md). Значения в базе пишутся
 * ровно как здесь.
 *
 * <p>Задача — корень иерархии и не бывает ни {@code AWAITING_PARENT}, ни {@code ABANDONED}:
 * поэтому перечисление отдельное от {@link TaskBatchStatus}. Терминальный статус не окончателен —
 * ручной перезапуск подзадачи возвращает задачу в {@link #AWAITING_CHILDREN}.
 */
public enum TaskStatus {

    /**
     * Ждёт захвата. Ждёт повтора или отложена — это тоже {@code PENDING} со временем «не раньше»
     * в будущем; отдельных статусов нет.
     */
    PENDING,

    /** Захвачена и работает над текущей фазой: обработка, раскрытие или сборка. */
    RUNNING,

    /** Раскрытие закончено, дети в работе; аренды задача не держит, следующая фаза — сборка. */
    AWAITING_CHILDREN,

    /** Выполнена. */
    SUCCEEDED,

    /** Выполнена, но часть детей упала или отменена. */
    WARNING,

    /** Не выполнена: попытки исчерпаны или повтор запрещён процессором. */
    FAILED,

    /** Работа не сделана из-за отмены. */
    CANCELLED,

    /** Выполнять не надо: так решил процессор или задачу пропустил движок. */
    SKIPPED
}
