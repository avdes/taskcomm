package xyz.avasilev.taskcomm.task.api;

import java.time.Instant;
import java.util.Optional;
import java.util.UUID;
import xyz.avasilev.taskcomm.execution.api.ExecutionRef;

/**
 * Подзадача: обработка <b>одного</b> бизнес-объекта. Минимальная единица работы и повтора;
 * самодостаточна — её повтор не требует ни группы, ни задачи.
 *
 * <p>Идентификаторы задачи и группы даны, чтобы потребитель мог вести собственное хранилище общих
 * данных группы, если дублировать их в каждую подзадачу дорого: своего такого хранилища у стартера
 * нет (docs/adr/0022-batch-data-placement.md).
 *
 * <p>Интерфейс, а не запись (docs/adr/0111-task-public-api-shape.md). Значения — снимок на момент
 * чтения.
 *
 * @param <U> один бизнес-объект — например, заказ
 */
public interface TaskUnit<U> {

    /**
     * Идентификатор подзадачи.
     *
     * @return идентификатор, UUIDv7
     */
    UUID id();

    /**
     * Задача, к которой относится подзадача.
     *
     * @return идентификатор задачи
     */
    UUID taskId();

    /**
     * Группа, к которой относится подзадача.
     *
     * @return идентификатор группы или пусто у задач с подзадачами без групп
     */
    Optional<UUID> batchId();

    /**
     * Дело задачи.
     *
     * @return ссылка на дело
     */
    ExecutionRef executionRef();

    /**
     * Тип задачи.
     *
     * @return тип задачи
     */
    String taskType();

    /**
     * Бизнес-объект подзадачи.
     *
     * @return нагрузка, восстановленная в тип из дженерика процессора
     */
    U payload();

    /**
     * Приоритет, унаследованный от родителя. Шкала по возрастанию: <b>меньше значит важнее</b>.
     *
     * @return приоритет, больше нуля
     */
    int priority();

    /**
     * Статус на момент чтения.
     *
     * @return статус подзадачи
     */
    TaskUnitStatus status();

    /**
     * Причина терминального статуса подзадачи.
     *
     * @return причина или пусто
     */
    Optional<String> statusDescription();

    /**
     * Время создания подзадачи по часам базы.
     *
     * @return время создания
     */
    Instant createdAt();
}
