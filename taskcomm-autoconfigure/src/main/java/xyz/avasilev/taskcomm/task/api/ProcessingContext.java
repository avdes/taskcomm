package xyz.avasilev.taskcomm.task.api;

import xyz.avasilev.taskcomm.execution.api.ExecutionRef;

/**
 * Контекст обработки — параметр каждого метода процессора задачи. Действителен только внутри вызова,
 * в который передан. Все методы отвечают из памяти, без запроса к базе.
 *
 * <p>Свой у подсистемы задач: у коммуникаций контекст свой, общего типа нет
 * (docs/adr/0010-separate-engines.md).
 */
public interface ProcessingContext {

    /**
     * Объявляет пропуск: выполнять не надо. Действует, только если метод затем вернулся нормально;
     * <b>исключение перебивает пропуск</b> — ошибка важнее. После вызова {@link #shouldStop()}
     * отвечает {@code true}.
     *
     * <p>Пропуск — исход, а не данные: значение, которое возвращает метод, сохраняется как результат
     * и при пропуске. Пропуск в сборке делает родителя {@code SKIPPED} поверх свода детей
     * (docs/adr/0082-skip-on-every-level.md).
     *
     * @param reason причина, обязательна; хранится в базе
     */
    void skip(String reason);

    /**
     * Запрещает повтор: если метод затем бросит исключение, попытка станет последней и сущность —
     * терминальной, без остатка лимита. Без последующего исключения не делает ничего.
     *
     * <p>Вызывать надо <b>до</b> броска — после броска уже некому. В отличие от {@link #skip(String)}
     * исход не объявляет, а меняет политику повторов; одинаковая форма методов симметрии не означает
     * (docs/adr/0062-non-retryable-failure.md).
     *
     * @param reason причина, обязательна; отличает «повторять запрещено» от «попытки исчерпаны»
     */
    void doNotRetry(String reason);

    /**
     * Сигнал прекращения: {@code true} — пора остановиться. Поднимается при отмене этой сущности
     * или её предка, при потере аренды и после собственного {@link #skip(String)}; причину метод
     * не сообщает — реакция одна. Об отмене узнаётся с задержкой до такта heartbeat.
     *
     * <p>Проверка добровольная и бесплатная — без запроса к базе. Поток процессора стартер не прерывает
     * никогда.
     *
     * @return {@code true}, если работу надо прекратить
     */
    boolean shouldStop();

    /**
     * Ссылка на дело обрабатываемой сущности. Обход ловушки неявной привязки: созданное в другом
     * потоке иначе попало бы в новое дело. Ссылку можно унести в любой поток и передать в метод
     * создания (docs/adr/0056-execution-ref.md).
     *
     * @return ссылка на текущее дело
     */
    ExecutionRef executionRef();

    /**
     * Номер текущей попытки среди попыток той же фазы с начала текущего цикла повторов, с единицы —
     * то, что считается в лимит повторов. Сборка после раскрытия начинается с единицы. Ручной
     * перезапуск начинает новый цикл, и номер снова единица
     * (docs/adr/0112-attempt-number-in-processing-context.md).
     *
     * @return номер попытки, не меньше единицы
     */
    int attemptNumber();

    /**
     * Повтор ли это: была ли у сущности более ранняя попытка той же фазы — за всю историю,
     * включая время до ручного перезапуска. После ручного перезапуска {@link #attemptNumber()}
     * равен единице, а этот метод отвечает {@code true}: побочные эффекты прежних попыток
     * перезапуск не отменяет.
     *
     * <p>Защиты от двойного выполнения признак не даёт: воркер, потерявший аренду, мог доработать
     * параллельно. Обработка обязана быть идемпотентной в любом случае.
     *
     * @return {@code true}, если эту фазу у сущности уже пытались выполнить
     */
    boolean isRetry();
}
