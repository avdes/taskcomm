package xyz.avasilev.taskcomm.task.api;

/**
 * Статус группы подзадач (docs/adr/0068-expansion-children-statuses.md). Значения в базе пишутся
 * ровно как здесь.
 *
 * <p>Набор задачи плюс два статуса ребёнка раскрытия. Совпадение с {@link TaskStatus} в остальном —
 * не повод для общего перечисления: недостижимое значение было бы пустой веткой {@code switch}.
 */
public enum TaskBatchStatus {

    /** Порождена, но попытка раскрытия задачи ещё не закрыта успехом; не захватывается, но незавершена. */
    AWAITING_PARENT,

    /** Ждёт захвата, в том числе повтора. */
    PENDING,

    /** Захвачена и работает над текущей фазой: раскрытие или сборка. */
    RUNNING,

    /** Раскрытие закончено, подзадачи в работе; аренды группа не держит. */
    AWAITING_CHILDREN,

    /** Выполнена. */
    SUCCEEDED,

    /** Выполнена, но часть подзадач упала или отменена. */
    WARNING,

    /** Не выполнена. */
    FAILED,

    /** Работа не сделана из-за отмены. */
    CANCELLED,

    /** Выполнять не надо. */
    SKIPPED,

    /** Дитя неуспешной попытки раскрытия: работа не начиналась и не начнётся; в агрегат не входит. */
    ABANDONED
}
