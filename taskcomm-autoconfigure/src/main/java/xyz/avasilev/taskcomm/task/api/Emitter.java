package xyz.avasilev.taskcomm.task.api;

/**
 * Приёмник детей при раскрытии: в {@code expand} — групп или подзадач, в {@code expandBatch} —
 * подзадач (docs/adr/0008-expansion-emitter.md, docs/adr/0032-no-business-key.md).
 *
 * <p>Дети не возвращаются списком, а отдаются по одному: стартер копит их в буфере и сбрасывает
 * пачками, каждую своей короткой транзакцией, — ни миллион строк в памяти, ни миллион в одной
 * транзакции. Отсюда раскрытие не атомарно; удалось ли оно, решает исход попытки, а не число детей.
 * Ноль детей — успешное раскрытие.
 *
 * <p>Действителен только внутри вызова, в который передан, и не потокобезопасен. Вызов после
 * возврата из метода — {@link IllegalStateException}. Если попытку раскрытия уже закрыл переподхват
 * истёкшей аренды, очередной {@code emit} тоже бросает исключение: дети этой попытки больше
 * не нужны.
 *
 * @param <T> нагрузка ребёнка
 */
public interface Emitter<T> {

    /**
     * Отдаёт одного ребёнка.
     *
     * @param payload нагрузка ребёнка
     * @throws IllegalStateException если вызов вне своего метода раскрытия или попытка уже закрыта
     */
    void emit(T payload);
}
